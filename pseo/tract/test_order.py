"""БАЗА КРУГА: позиция ключа неприкосновенна.

Требование юзера (2026-07-25), дословно: «правка должна делать только одно — правильно
отсчитывать ключ в круге, но не менять его позицию в стартовом порядке. 11 ключ всегда 11.
И всегда идёт после 1-10 ключей, даже если там кто-то выпадает».

То есть выдача идёт ПОЗИЦИОННО по списку — как генератор экстрактора
(extraction.iter_model_key_pairs: `for api_key, kh in hashed` без пересортировки).
Выпавший ключ теряет свой ход и возвращается НА СВОЁ МЕСТО, а не в голову очереди.

⚠️ Почему тест обязан ронять ключ в кулдаун: пока ВСЕ ключи живы, позиционный обход и
сортировка по давности дают ОДНУ И ТУ ЖЕ последовательность, и никакой тест их не различит.
Расходятся они ровно в одном месте — когда ключ выпал и вернулся: позиционный отдаёт ему
его место, сортировка по давности — первое место (у него самый старый штамп).
Прежний тест в test_broker.py проверял лишь «в окне из N грантов N разных ключей» — этот
инвариант выполняется и той и другой схемой, поэтому подмену базы он пропустил.

⚠️ Требует KB_DB на ОТДЕЛЬНУЮ базу: тест сносит файл.
⚠️ И KB_GROUP_SIZE=0: тест про БАЗОВЫЙ круг по всему пулу. Со звеньями (по умолчанию 4)
   пять ключей режутся на два звена, и ждать сквозной обход 0-4 бессмысленно — звенья
   проверяет test_group.py. Без явного нуля тест откажется стартовать, а не соврёт.
  KB_DB=/tmp/kb_order.db KB_GRANT_MAX=0.01 KB_GRANT_MIN=0.01 KB_GROUP_SIZE=0 \
  python test_order.py
"""

import os
import sys
import time

import keybroker as k

M = "gemini-3.1-flash-lite"
KEYS = ["key-%d" % i for i in range(5)]
N = len(KEYS)


def grant():
    """Один грант. (None, 0.0) — это очередь по такту, а не отказ: ждём и повторяем."""
    for _ in range(2000):
        key, wait = k.acquire("t", "background", M, KEYS)
        if key is not None:
            return KEYS.index(key)
        if wait == 0.0:
            time.sleep(0.005)
            continue
        raise SystemExit("acquire отдал %r — ключей нет, тест не про это" % (wait,))
    raise SystemExit("не дождались гранта")


def seq(n):
    return [grant() for _ in range(n)]


def cooldown(idx, secs):
    c = k._conn()
    c.execute("BEGIN IMMEDIATE")
    c.execute(
        "INSERT INTO key_clock(key_hash, cooldown_until) VALUES(?,?) "
        "ON CONFLICT(key_hash) DO UPDATE SET cooldown_until=excluded.cooldown_until",
        (k._kh(KEYS[idx]), time.time() + secs),
    )
    c.execute("COMMIT")
    c.close()


def expect(got, want, what):
    ok = got == want
    print(
        "%-46s получили %s\n%-46s ждали   %s  %s"
        % (what, got, "", want, "OK" if ok else "← ПРОВАЛ")
    )
    return ok


if __name__ == "__main__":
    if not os.environ.get("KB_DB"):
        sys.exit("ОТКАЗ: задай KB_DB на тестовую базу — тест сносит файл")
    if k.GROUP_SIZE:
        sys.exit(
            "ОТКАЗ: тест про БАЗОВЫЙ круг по всему пулу, а стоит KB_GROUP_SIZE=%d. "
            "Запускай с KB_GROUP_SIZE=0; звенья проверяет test_group.py" % k.GROUP_SIZE
        )
    try:
        os.remove(k.DB)
    except OSError:
        pass
    k.init()
    ok = True

    # 1. Чистый круг: строго по списку, дважды подряд.
    ok &= expect(seq(2 * N), [0, 1, 2, 3, 4] * 2, "1. два полных круга подряд")

    # 2. Ключ 1 выпал (кулдаун). Остальные держат СВОИ позиции, 1 просто пропускается.
    #    Шаг 1 кончился на ключе 4 → продолжаем с 0, единицу перешагиваем.
    cooldown(1, 60)
    ok &= expect(
        seq(8), [0, 2, 3, 4, 0, 2, 3, 4], "2. ключ 1 в кулдауне — его пропускают"
    )

    # 3. ⭐ РЕШАЮЩИЙ. Ключ 1 вернулся. Шаг 2 кончился на 4 → идём 0, и ТОЛЬКО ПОТОМ 1,
    #    на своём месте. ⛔ Сортировка по давности отдаёт ему ПЕРВЫЙ ход: пока он сидел,
    #    штампы остальных обновлялись, и его стал самым старым. Здесь это провал.
    cooldown(1, -1)  # кулдаун истёк
    ok &= expect(
        seq(6), [0, 1, 2, 3, 4, 0], "3. ключ 1 вернулся НА СВОЁ МЕСТО, не в голову"
    )

    # 4. Круг замкнулся и идёт дальше без перекосов: шаг 3 кончился на 0 → 1,2,3,4,0.
    ok &= expect(seq(N), [1, 2, 3, 4, 0], "4. круг продолжается без перекоса")

    print(
        "\nVERDICT:",
        "OK — позиция ключа неприкосновенна" if ok else "FAIL — база нарушена",
    )
    sys.exit(0 if ok else 1)
