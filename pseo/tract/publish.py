"""publish.py — звено 8, шаг 3: атомарная подмена дерева на живом сайте.

PLAN.md §3.2, шаг 3. Живой `site/online` — то, что nginx-контейнер (`bots-pseosite`)
отдаёт прямо сейчас реальным посетителям (bind-mount смотрит НА ЭТУ папку, не на
символическую ссылку). `rsync --delete` прямо в неё оставляет окно «половина старая,
половина новая» на десятки секунд — с sitemap/hreflang, ссылающимися на ещё не
скопированные страницы, и с риском НАВСЕГДА разбитого дерева при обрыве на середине
(контейнер передеплоился, диск кончился — в этом проекте уже бывало не раз).

Вместо этого: `rsync` собирает НОВОЕ дерево РЯДОМ (`<live>_new`, не поверх живого), и
только когда копирование ПОЛНОСТЬЮ завершилось — подмена. Здесь — сама подмена, две
`os.rename` (атомарная ФС-операция, не копирование): первая уводит живую папку в
сторону (`<live>_prev_<ts>`, НЕ удаляется — путь отката), вторая ставит новую на её
место. Между ними живой путь долю секунды не существует вовсе — короче любого rsync,
но не ноль; для истинного нуля нужен symlink-индирекшн (`site/current -> online_vN`),
что требует одноразовой ручной правки bind-mount в Dokploy — не делаем без факта, что
голый `rename` не подхватывается контейнером сам (проверка — отдельно, на VPS).
"""

import os
import shutil
import time


def swap_in(staging: str, live: str, keep_prev: bool = True) -> str | None:
    """Подменить `live` на `staging`. Возвращает путь к отведённой старой версии
    (или `None`, если `live` не существовал — самая первая публикация) — чистить её
    или нет, решает вызывающий, не эта функция.

    ⛔ Готовность `staging` (скопировалось ли ПОЛНОСТЬЮ) — забота вызывающего. Здесь
    только механика подмены, она не гадает, что считать «достаточно скопировано».
    """
    if not os.path.isdir(staging):
        raise FileNotFoundError(f"нет свежего дерева для подмены: {staging}")
    prev = None
    if os.path.exists(live):
        prev = f"{live}_prev_{int(time.time())}"
        os.rename(live, prev)
    try:
        os.rename(staging, live)
    except Exception:
        # подмена не удалась — вернуть старое НА МЕСТО: живой путь не должен
        # остаться вовсе без каталога из-за нашей же попытки его обновить
        if prev:
            os.rename(prev, live)
        raise
    if prev and not keep_prev:
        shutil.rmtree(prev)
        prev = None
    return prev
