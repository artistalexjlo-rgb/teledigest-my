"""Сторож: копия справочника стран в `pseo/builder/` дословно равна файлу бота.

Почему копия, а не импорт из `src/teledigest/`: `pseo` — самодостаточное дерево (свои дубли
ртов, свои импорты по пути), и ходить за данными в пакет бота ему незачем. Цена локальности —
второе место, за которым надо следить; следит машина, а не моя память.

Замер, на котором держится решение (2026-08-11): справочник правили ПЯТЬ раз за четыре месяца
(24.04 завели, 15.05 добили полноту ISO, 18.05 свели английские имена, 24.05 добавили
`any → Universal`), и с мая — ни разу. Дрейф редкий, но не нулевой: пять поводов забыть.

⛔ Что НЕ является поводом ослабить этот тест: «да там нечему меняться». Дефект, из-за которого
всё началось, был именно таким — своя табличка на 35 стран из 249, которую никто не сверял, и
она отставала месяц, печатая на живом сайте сырые коды.
"""

import pathlib

HERE = pathlib.Path(__file__).resolve().parent
COPY = HERE / "country_codes.py"
ORIGIN = HERE.parent.parent / "src" / "teledigest" / "country_codes.py"


def _norm(p: pathlib.Path) -> bytes:
    """Сравниваем без оглядки на перевод строки: git на Windows отдаёт CRLF в рабочей копии."""
    return p.read_bytes().replace(b"\r\n", b"\n")


def test_copy_exists():
    assert (
        COPY.exists()
    ), "справочник рядом с pages.py пропал — имена стран поедут кодами"
    assert ORIGIN.exists(), "исходник справочника у бота пропал — проверять нечего"


def test_copy_is_byte_identical():
    """Разъехались — синхронизировать копию, а не править тест."""
    assert _norm(COPY) == _norm(ORIGIN), (
        "копия справочника отстала от `src/teledigest/country_codes.py`: "
        "скопировать файл заново (он данные, конфликтов правок в нём не бывает)"
    )


def test_copy_has_no_dependencies():
    """Справочник обязан оставаться данными: из импортов только stdlib. Иначе копия
    притащит в образ пульта половину бота."""
    src = _norm(COPY).decode("utf-8")
    imports = [
        ln.strip()
        for ln in src.splitlines()
        if ln.startswith("import ") or ln.startswith("from ")
    ]
    assert imports == ["import logging"], f"справочник оброс зависимостями: {imports}"
