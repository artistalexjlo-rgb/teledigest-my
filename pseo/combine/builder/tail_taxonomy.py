# Форма «<одно дело>: пример, пример» нормальна, и отличить её от перечня тем по числу
# запятых нельзя. Оставляем то, что на контроле не дало ни одной ложной: словарь сборных
# слов и рубрику-без-предмета.


def bad_label(z):
    """Метка — брак нарезки? Возвращает причину (строку) или None.

    Причину возвращаем, а не True: она уходит в лог, иначе отсев снова будет молчаливым —
    ровно так 33 пустых хаба год жили незамеченными.

    Проверено на КОНТРОЛЕ (все 1 889 меток корпуса, 14.08): правило ловит сборные метки и
    не задевает конкретные. Числа — в канон §0.13.
    """
    t = (z or "").strip().lower().replace("ё", "е")
    if not t:
        return "пустая метка"
    core = t.strip(" .:;!?-—()[]«»\"'")
    for w in _JUNK_LABEL:
        if core == w or core.startswith(w + " ") or core.startswith(w + ","):
            return f"сборное слово: {w}"
    if core.startswith("особенности") and len(core.split()) <= 2:
        return "рубрика без предмета: особенности"
    # Метка = имя РАЗДЕЛА: это рубрика, а не запрос человека. Раздел и так есть на хабе.
    if core in {n.lower().replace("ё", "е") for n in SHELF_NAMES}:
        return "метка повторяет имя раздела"
    return None
