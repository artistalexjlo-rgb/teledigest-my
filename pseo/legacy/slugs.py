"""slugs.py — ХВОСТ АДРЕСА. Единственное место, где строится слаг.

Живёт отдельным модулем, потому что читают его ДВА дерева: сборщик страниц (`pages.py`)
и переводчик (`facet_lang.py --stamp-keys`, штампующий ключи адресов). Пока `slug()` жил
внутри pages.py, комбайну он был недоступен — в `combine/builder/` файла pages.py нет.

⛔ Правило адреса — канон BUILDER_RULES §0.11: `/<язык>/<страна>/` + ОДИНАКОВЫЙ английский
хвост. Транслит ниже — не адрес, а ФОЛБЭК для узлов, которым ключ ещё не проштампован.
"""

import re

# RU→latin транслит для слагов: URL латиницей (money-качество), не кириллический %-суп
_TR = {
    "а": "a",
    "б": "b",
    "в": "v",
    "г": "g",
    "д": "d",
    "е": "e",
    "ё": "e",
    "ж": "zh",
    "з": "z",
    "и": "i",
    "й": "y",
    "к": "k",
    "л": "l",
    "м": "m",
    "н": "n",
    "о": "o",
    "п": "p",
    "р": "r",
    "с": "s",
    "т": "t",
    "у": "u",
    "ф": "f",
    "х": "h",
    "ц": "ts",
    "ч": "ch",
    "ш": "sh",
    "щ": "sch",
    "ъ": "",
    "ы": "y",
    "ь": "",
    "э": "e",
    "ю": "yu",
    "я": "ya",
}


def slug_or_none(t):
    """Слаг метки или None, если пригодных символов не осталось НИ ОДНОГО.

    ⛔ Различать эти два случая обязательно. `_TR` умеет только кириллицу, поэтому у
    китайской, японской, корейской, арабской, деванагари и тайской метки вычищается ВСЁ
    и остаётся пустая строка. Раньше на этом месте стоял фолбэк `or "tema"`, и все
    страницы гео получали ОДИН адрес — а уникализации адресов в pages.py нет нигде,
    значит они молча перезаписывали друг друга: ~90 страниц на язык вместо ~1843.
    Пустой результат = адреса НЕТ, и вызывающий обязан страницу пропустить, а не выдумать
    ей имя. Настоящий адрес для таких языков даёт `facet_lang.py --stamp-keys`.
    """
    t = "".join(_TR.get(ch, ch) for ch in (t or "").lower())
    return re.sub(r"[^a-z0-9]+", "-", t).strip("-")[:40] or None


def slug(t):
    """Слаг с фолбэком «tema». Оставлен для мест, где адрес не строится (имена файлов,
    ключи полок из таксономии). Для АДРЕСА страницы звать `slug_or_none` через
    `pages.addr` — иначе вернётся коллизия вместо честного отказа."""
    return slug_or_none(t) or "tema"
